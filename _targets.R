# 以项目根目录启动
if (!requireNamespace("targets", quietly = TRUE)) stop("请先安装targets：install.packages('targets')")
targets::tar_source("R")
data.table::setDTthreads(1L)
config_dir <- Sys.getenv("TRANSCRIPTOME_CONFIG_DIR", unset = "config")
targets::tar_option_set(packages = c("edgeR", "ggplot2", "data.table"), memory = "transient", garbage_collection = FALSE, error = "stop")

list(
  targets::tar_target(paths_config_file, file.path(config_dir, "paths.yml"), format = "file"),
  targets::tar_target(paths_config, read_config_lst(paths_config_file)),
  targets::tar_target(variables_config_file, file.path(config_dir, "variables.yml"), format = "file"),
  targets::tar_target(variables_config, read_config_lst(variables_config_file)),
  targets::tar_target(comparisons_config_file, file.path(config_dir, "comparisons.yml"), format = "file"),
  targets::tar_target(comparisons_config, read_config_lst(comparisons_config_file)),
  targets::tar_target(analysis_config_file, file.path(config_dir, "analysis.yml"), format = "file"),
  targets::tar_target(analysis_config, read_config_lst(analysis_config_file)),
  targets::tar_target(model_settings, analysis_config$model),
  targets::tar_target(deg_thresholds, analysis_config$filter),
  targets::tar_target(reference_config_file, file.path(config_dir, "reference.yml"), format = "file"),
  targets::tar_target(reference_config, read_config_lst(reference_config_file)),
  targets::tar_target(go_settings, reference_config[c("reference_species", "tax_id", "kegg_code", "go_ontology", "go_ancestors")]),
  targets::tar_target(kegg_settings, reference_config[c("kegg_code", "run_kegg", "require_kegg", "kegg_term2gene", "kegg_term2name", "kegg_refresh")]),
  targets::tar_target(enrichment_config_file, file.path(config_dir, "enrichment.yml"), format = "file"),
  targets::tar_target(enrichment_settings, read_config_lst(enrichment_config_file)),
  targets::tar_target(figures_config_file, file.path(config_dir, "figures.yml"), format = "file"),
  targets::tar_target(figures_config, read_config_lst(figures_config_file)),
  targets::tar_target(figure_style, figures_config$style),
  targets::tar_target(figure_display, figures_config$display),
  targets::tar_target(export_settings, figures_config$export),
  targets::tar_target(output_dir, project_path(paths_config$output_dir)),
  targets::tar_target(count_file, project_path(paths_config$count_file), format = "file"),
  targets::tar_target(sample_file, project_path(paths_config$sample_file), format = "file"),
  targets::tar_target(gtf_file, project_path(paths_config$gtf_file), format = "file"),
  targets::tar_target(gene2go_file, project_path(paths_config$gene2go_file), format = "file"),
  targets::tar_target(engine_files, file.path("analysis_scripts", "lib", c("Rscript_R6_transcriptome_base.R", "Rscript_R6_transcriptome_class.R",
                                                                         "compatibility.R", "project_helpers.R")), format = "file"),
  targets::tar_target(plot_helper_file, file.path("analysis_scripts", "lib", "plot_helpers.R"), format = "file"),
  targets::tar_target(count_data, read_count_data_lst(count_file)),
  targets::tar_target(sample_metadata, read_sample_metadata_tbl(sample_file, variables_config)),
  targets::tar_target(sample_alignment, check_sample_alignment(sample_metadata, count_data)),
  targets::tar_target(comparison_jobs, { sample_alignment; make_comparison_jobs_lst(sample_metadata, comparisons_config) }, iteration = "list"),
  targets::tar_target(input_files, export_metadata_files(sample_metadata, comparison_jobs, output_dir), format = "file"),
  targets::tar_target(annotation_go, read_go_annotation_lst(gtf_file, gene2go_file, go_settings, engine_files)),
  targets::tar_target(annotation_files, export_annotation_files(annotation_go, output_dir), format = "file"),
  targets::tar_target(kegg_source_files, kegg_input_paths(kegg_settings, reference_config_file), format = "file"),
  targets::tar_target(kegg_snapshot_files, build_kegg_snapshot_paths(kegg_settings, kegg_source_files, output_dir), format = "file"),
  targets::tar_target(background_jobs, make_background_jobs_lst(annotation_go, kegg_snapshot_files), iteration = "list"),
  targets::tar_target(qc_data, { sample_alignment; calc_qc_lst(count_data, sample_metadata) }),
  targets::tar_target(qc_files, export_qc_files(qc_data, sample_metadata, figure_display, figure_style, export_settings, output_dir), format = "file"),
  targets::tar_target(deg_fit, fit_comparison_lst(count_data, comparison_jobs, model_settings, engine_files), pattern = map(comparison_jobs),
    iteration = "list"),
  targets::tar_target(annotated_deg, attach_gene_annotation_tbl(deg_fit, annotation_go$annotation), pattern = map(deg_fit), iteration = "list"),
  targets::tar_target(selected_deg, select_deg_lst(annotated_deg, deg_thresholds), pattern = map(annotated_deg), iteration = "list"),
  targets::tar_target(ranked_genes, rank_genes_lst(annotated_deg), pattern = map(annotated_deg), iteration = "list"),
  targets::tar_target(deg_files, export_deg_files(annotated_deg, selected_deg, output_dir), pattern = map(annotated_deg, selected_deg), format = "file"),
  targets::tar_target(deg_plot_files, export_deg_plot_files(annotated_deg, deg_thresholds, figure_style, export_settings, output_dir),
                      pattern = map(annotated_deg), format = "file"),
  targets::tar_target(deg_combined_files, export_deg_combined_files(annotated_deg, deg_thresholds, figure_style, export_settings, output_dir,
    figure_display), format = "file"),
  targets::tar_target(gene_set_files, export_gene_set_files(selected_deg, engine_files, plot_helper_file, figure_style, export_settings, output_dir,
    figure_display), format = "file"),
  targets::tar_target(expression_heatmap_files, export_expression_heatmap_files(qc_data, selected_deg, sample_metadata, annotation_go,
                      figure_display, figure_style, export_settings, output_dir), format = "file"),
  targets::tar_target(ora_up, run_ora_lst(selected_deg, background_jobs, enrichment_settings, "Up"),
                      pattern = cross(selected_deg, background_jobs), iteration = "list"),
  targets::tar_target(ora_down, run_ora_lst(selected_deg, background_jobs, enrichment_settings, "Down"),
                      pattern = cross(selected_deg, background_jobs), iteration = "list"),
  targets::tar_target(gsea, run_gsea_lst(ranked_genes, background_jobs, enrichment_settings), pattern = cross(ranked_genes, background_jobs),
    iteration = "list"),
  targets::tar_target(ora_up_table, collect_enrichment_tbl(ora_up), pattern = map(ora_up), iteration = "list"),
  targets::tar_target(ora_down_table, collect_enrichment_tbl(ora_down), pattern = map(ora_down), iteration = "list"),
  targets::tar_target(gsea_table, collect_enrichment_tbl(gsea), pattern = map(gsea), iteration = "list"),
  targets::tar_target(enrichment_catalog, collect_enrichment_catalog_tbl(ora_up_table, ora_down_table, gsea_table)),
  targets::tar_target(ora_up_files, export_enrichment_files(ora_up, output_dir), pattern = map(ora_up), format = "file"),
  targets::tar_target(ora_down_files, export_enrichment_files(ora_down, output_dir), pattern = map(ora_down), format = "file"),
  targets::tar_target(gsea_files, export_enrichment_files(gsea, output_dir), pattern = map(gsea), format = "file"),
  targets::tar_target(gsea_records, read_enrichment_record_lst(gsea_files), pattern = map(gsea_files), iteration = "list"),
  targets::tar_target(ora_plot_files, export_ora_plot_files(ora_up, ora_down, annotation_go$annotation, deg_thresholds, figure_display,
                      figure_style, export_settings, engine_files, plot_helper_file, output_dir), pattern = map(ora_up, ora_down), format = "file"),
  targets::tar_target(gsea_plot_files, export_gsea_plot_files(gsea, annotation_go$annotation, deg_thresholds, figure_display,
                      figure_style, export_settings, engine_files, plot_helper_file, output_dir), pattern = map(gsea), format = "file"),
  targets::tar_target(display_selections, select_display_terms_lst(enrichment_catalog, deg_thresholds, figure_display, comparison_jobs, background_jobs),
    iteration = "list"),
  targets::tar_target(comparative_files, export_comparative_files(enrichment_catalog, display_selections, comparison_jobs, deg_thresholds,
                      figure_display, figure_style, export_settings, output_dir), pattern = map(display_selections), format = "file"),
  targets::tar_target(comparative_combined_files, export_comparative_combined_files(enrichment_catalog, display_selections, comparison_jobs,
                      deg_thresholds, figure_display, figure_style, export_settings, output_dir), format = "file"),
  targets::tar_target(curve_combined_files, export_curve_combined_files(gsea_records, comparison_jobs, deg_thresholds, figure_display,
                      figure_style, export_settings, engine_files, plot_helper_file, output_dir), format = "file"),
  targets::tar_target(pathview_files, export_pathview_files(gsea_records, deg_thresholds, figure_display, reference_config,
                      export_settings, output_dir), format = "file"),
  targets::tar_target(summary_files, export_run_summary_files(c(input_files, annotation_files, qc_files, deg_files, deg_plot_files,
                      deg_combined_files, gene_set_files, expression_heatmap_files, ora_up_files, ora_down_files, gsea_files,
                      ora_plot_files, gsea_plot_files, comparative_files, comparative_combined_files, curve_combined_files, pathview_files),
                      comparison_jobs, sample_metadata, reference_config, model_settings, deg_thresholds, enrichment_settings, figures_config, output_dir),
                        format = "file")
)
